-- V3 — Trips & Members (M3): TRIPS, TRIP_MEMBERS, TRIP_INVITATIONS (SPEC §6 Modules 2-3).
-- Member-centric money: every later money reference points at TRIP_MEMBERS.ID, not USERS.ID,
-- so a group can split with ghost members (USER_ID NULL).

-- ─── TRIPS ──────────────────────────────────────────────────────────────────
CREATE TABLE TRIPS (
    ID             NUMBER(19)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID            VARCHAR2(36)  NOT NULL,
    NAME           VARCHAR2(200) NOT NULL,
    DESCRIPTION    VARCHAR2(2000),
    DESTINATION    VARCHAR2(300),
    TRIP_TYPE      VARCHAR2(20)  DEFAULT 'OTHER' NOT NULL,   -- TripType
    START_DATE     DATE,
    END_DATE       DATE,
    TIMEZONE       VARCHAR2(64)  DEFAULT 'Asia/Ho_Chi_Minh' NOT NULL,
    BASE_CURRENCY  VARCHAR2(3)   DEFAULT 'VND' NOT NULL,
    STATUS         VARCHAR2(20)  DEFAULT 'PLANNING' NOT NULL, -- TripStatus
    OWNER_ID       NUMBER(19)   NOT NULL,
    CREATED_AT     TIMESTAMP,
    CREATED_BY     NUMBER(19),
    UPDATED_AT     TIMESTAMP,
    UPDATED_BY     NUMBER(19),
    VERSION        NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED     NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TRIPS PRIMARY KEY (ID),
    CONSTRAINT FK_TRIPS_OWNER FOREIGN KEY (OWNER_ID) REFERENCES USERS (ID)
);
CREATE UNIQUE INDEX UK_TRIPS_RID ON TRIPS (RID);
CREATE INDEX IX_TRIPS_OWNER ON TRIPS (OWNER_ID);
CREATE INDEX IX_TRIPS_STATUS ON TRIPS (STATUS);

-- ─── TRIP_MEMBERS (USER_ID NULL = ghost member) ────────────────────────────────
CREATE TABLE TRIP_MEMBERS (
    ID            NUMBER(19)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID           VARCHAR2(36)  NOT NULL,
    TRIP_ID       NUMBER(19)   NOT NULL,
    USER_ID       NUMBER(19),                                -- NULL = ghost (no account)
    DISPLAY_NAME  VARCHAR2(150) NOT NULL,
    ROLE          VARCHAR2(20)  NOT NULL,                    -- MemberRole
    JOINED_AT     TIMESTAMP,
    CREATED_AT    TIMESTAMP,
    CREATED_BY    NUMBER(19),
    UPDATED_AT    TIMESTAMP,
    UPDATED_BY    NUMBER(19),
    VERSION       NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED    NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TRIP_MEMBERS PRIMARY KEY (ID),
    CONSTRAINT FK_TRIP_MEMBERS_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID),
    CONSTRAINT FK_TRIP_MEMBERS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);
CREATE UNIQUE INDEX UK_TRIP_MEMBERS_RID ON TRIP_MEMBERS (RID);
CREATE INDEX IX_TRIP_MEMBERS_TRIP ON TRIP_MEMBERS (TRIP_ID);
CREATE INDEX IX_TRIP_MEMBERS_USER ON TRIP_MEMBERS (USER_ID);
-- One live membership per (trip, real user); ghosts (USER_ID NULL) are exempt.
CREATE UNIQUE INDEX UK_TRIP_MEMBERS_TRIP_USER ON TRIP_MEMBERS (
    CASE WHEN USER_ID IS NOT NULL AND IS_DELETED = 0 THEN TRIP_ID END,
    CASE WHEN USER_ID IS NOT NULL AND IS_DELETED = 0 THEN USER_ID END);

-- ─── TRIP_INVITATIONS (link / QR token) ────────────────────────────────────────
CREATE TABLE TRIP_INVITATIONS (
    ID            NUMBER(19)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID           VARCHAR2(36)  NOT NULL,
    TRIP_ID       NUMBER(19)   NOT NULL,
    TOKEN         VARCHAR2(64)  NOT NULL,                    -- embedded in invite link/QR
    ROLE          VARCHAR2(20)  NOT NULL,                    -- role granted on accept
    EXPIRES_AT    TIMESTAMP    NOT NULL,
    MAX_USES      NUMBER(5)     DEFAULT 1 NOT NULL,
    USED_COUNT    NUMBER(5)     DEFAULT 0 NOT NULL,
    CREATED_AT    TIMESTAMP,
    CREATED_BY    NUMBER(19),
    UPDATED_AT    TIMESTAMP,
    UPDATED_BY    NUMBER(19),
    VERSION       NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED    NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TRIP_INVITATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_TRIP_INVITATIONS_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID)
);
CREATE UNIQUE INDEX UK_TRIP_INVITATIONS_RID ON TRIP_INVITATIONS (RID);
CREATE INDEX IX_TRIP_INVITATIONS_TRIP ON TRIP_INVITATIONS (TRIP_ID);
CREATE UNIQUE INDEX UK_TRIP_INVITATIONS_TOKEN ON TRIP_INVITATIONS (
    CASE WHEN IS_DELETED = 0 THEN TOKEN END);
