-- V5 — Money (M5): BUDGETS, EXPENSES, EXPENSE_SHARES (SPEC §7 Modules 8, 9, 11).
-- Money is NUMBER(19,4); exchange rate NUMBER(19,8). AMOUNT_BASE is the snapshot
-- amount * rate in the trip base currency (computed in the service, never recomputed).
-- Money references point at TRIP_MEMBERS.ID (member-centric, supports ghost members).

-- ─── BUDGETS (planned, per category, in base currency) ──────────────────────
CREATE TABLE BUDGETS (
    ID              NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID             VARCHAR2(36)  NOT NULL,
    TRIP_ID         NUMBER(19)    NOT NULL,
    CATEGORY        VARCHAR2(20)  NOT NULL,                    -- Category
    PLANNED_AMOUNT  NUMBER(19,4)  NOT NULL,
    CREATED_AT      TIMESTAMP,
    CREATED_BY      NUMBER(19),
    UPDATED_AT      TIMESTAMP,
    UPDATED_BY      NUMBER(19),
    VERSION         NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED      NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_BUDGETS PRIMARY KEY (ID),
    CONSTRAINT FK_BUDGETS_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID)
);
CREATE UNIQUE INDEX UK_BUDGETS_RID ON BUDGETS (RID);
CREATE INDEX IX_BUDGETS_TRIP ON BUDGETS (TRIP_ID);
-- At most one live budget per (trip, category) — soft-deleted rows are exempt.
CREATE UNIQUE INDEX UK_BUDGETS_TRIP_CATEGORY ON BUDGETS (
    CASE WHEN IS_DELETED = 0 THEN TRIP_ID END,
    CASE WHEN IS_DELETED = 0 THEN CATEGORY END);

-- ─── EXPENSES ───────────────────────────────────────────────────────────────
CREATE TABLE EXPENSES (
    ID              NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID             VARCHAR2(36)  NOT NULL,
    TRIP_ID         NUMBER(19)    NOT NULL,
    TITLE           VARCHAR2(200) NOT NULL,
    CATEGORY        VARCHAR2(20)  NOT NULL,                    -- Category
    EXPENSE_TYPE    VARCHAR2(20)  DEFAULT 'PLANNED' NOT NULL,  -- ExpenseType
    CURRENCY        VARCHAR2(3)   NOT NULL,
    AMOUNT          NUMBER(19,4)  NOT NULL,                    -- original currency
    EXCHANGE_RATE   NUMBER(19,8)  NOT NULL,                    -- snapshot to base currency
    AMOUNT_BASE     NUMBER(19,4)  NOT NULL,                    -- = AMOUNT * EXCHANGE_RATE
    PAYER_ID        NUMBER(19)    NOT NULL,                    -- TRIP_MEMBERS.ID
    PLACE_ID        NUMBER(19),
    PAID_FROM_FUND  NUMBER(1)     DEFAULT 0 NOT NULL,
    NOTE            VARCHAR2(2000),
    SPENT_AT        TIMESTAMP     NOT NULL,                    -- UTC
    CREATED_AT      TIMESTAMP,
    CREATED_BY      NUMBER(19),
    UPDATED_AT      TIMESTAMP,
    UPDATED_BY      NUMBER(19),
    VERSION         NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED      NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EXPENSES PRIMARY KEY (ID),
    CONSTRAINT FK_EXPENSES_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID),
    CONSTRAINT FK_EXPENSES_PAYER FOREIGN KEY (PAYER_ID) REFERENCES TRIP_MEMBERS (ID),
    CONSTRAINT FK_EXPENSES_PLACE FOREIGN KEY (PLACE_ID) REFERENCES PLACES (ID)
);
CREATE UNIQUE INDEX UK_EXPENSES_RID ON EXPENSES (RID);
CREATE INDEX IX_EXPENSES_TRIP_CATEGORY ON EXPENSES (TRIP_ID, CATEGORY);
CREATE INDEX IX_EXPENSES_PAYER ON EXPENSES (PAYER_ID);
CREATE INDEX IX_EXPENSES_TRIP_SPENT ON EXPENSES (TRIP_ID, SPENT_AT);

-- ─── EXPENSE_SHARES (who owes what for a personal expense) ───────────────────
CREATE TABLE EXPENSE_SHARES (
    ID           NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID          VARCHAR2(36)  NOT NULL,
    EXPENSE_ID   NUMBER(19)    NOT NULL,
    MEMBER_ID    NUMBER(19)    NOT NULL,                       -- TRIP_MEMBERS.ID
    SHARE_BASE   NUMBER(19,4)  NOT NULL,                       -- base currency
    CREATED_AT   TIMESTAMP,
    CREATED_BY   NUMBER(19),
    UPDATED_AT   TIMESTAMP,
    UPDATED_BY   NUMBER(19),
    VERSION      NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED   NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EXPENSE_SHARES PRIMARY KEY (ID),
    CONSTRAINT FK_EXPENSE_SHARES_EXPENSE FOREIGN KEY (EXPENSE_ID) REFERENCES EXPENSES (ID),
    CONSTRAINT FK_EXPENSE_SHARES_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES TRIP_MEMBERS (ID)
);
CREATE UNIQUE INDEX UK_EXPENSE_SHARES_RID ON EXPENSE_SHARES (RID);
CREATE INDEX IX_EXPENSE_SHARES_EXPENSE ON EXPENSE_SHARES (EXPENSE_ID);
CREATE INDEX IX_EXPENSE_SHARES_MEMBER ON EXPENSE_SHARES (MEMBER_ID);
