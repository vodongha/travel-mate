-- V4 — Planning (M4): PLACES, EVENTS, TRANSPORTS, ACCOMMODATIONS, CHECKLIST_ITEMS
-- (SPEC §7 Modules 4-7, 12). All trip-scoped; FKs point at internal IDs.
-- Ticket/booking QR codes are stored as the decoded STRING (QR_DATA), never as an image (SPEC §2.7).

-- ─── PLACES ─────────────────────────────────────────────────────────────────
CREATE TABLE PLACES (
    ID          NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID         VARCHAR2(36)  NOT NULL,
    TRIP_ID     NUMBER(19),                                  -- NULL = shared catalog (unused for now)
    NAME        VARCHAR2(200) NOT NULL,
    ADDRESS     VARCHAR2(500),
    LATITUDE    NUMBER(10,7),
    LONGITUDE   NUMBER(10,7),
    PLACE_TYPE  VARCHAR2(20)  DEFAULT 'OTHER' NOT NULL,       -- PlaceType
    CREATED_AT  TIMESTAMP,
    CREATED_BY  NUMBER(19),
    UPDATED_AT  TIMESTAMP,
    UPDATED_BY  NUMBER(19),
    VERSION     NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED  NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PLACES PRIMARY KEY (ID),
    CONSTRAINT FK_PLACES_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID)
);
CREATE UNIQUE INDEX UK_PLACES_RID ON PLACES (RID);
CREATE INDEX IX_PLACES_TRIP ON PLACES (TRIP_ID);
CREATE INDEX IX_PLACES_TYPE ON PLACES (PLACE_TYPE);

-- ─── EVENTS (timeline) ──────────────────────────────────────────────────────
CREATE TABLE EVENTS (
    ID          NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID         VARCHAR2(36)  NOT NULL,
    TRIP_ID     NUMBER(19)    NOT NULL,
    TITLE       VARCHAR2(200) NOT NULL,
    EVENT_TYPE  VARCHAR2(20)  DEFAULT 'OTHER' NOT NULL,       -- EventType
    START_TIME  TIMESTAMP     NOT NULL,                       -- UTC
    END_TIME    TIMESTAMP,                                    -- UTC, nullable
    PLACE_ID    NUMBER(19),
    NOTE        VARCHAR2(2000),
    CREATED_AT  TIMESTAMP,
    CREATED_BY  NUMBER(19),
    UPDATED_AT  TIMESTAMP,
    UPDATED_BY  NUMBER(19),
    VERSION     NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED  NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EVENTS PRIMARY KEY (ID),
    CONSTRAINT FK_EVENTS_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID),
    CONSTRAINT FK_EVENTS_PLACE FOREIGN KEY (PLACE_ID) REFERENCES PLACES (ID)
);
CREATE UNIQUE INDEX UK_EVENTS_RID ON EVENTS (RID);
CREATE INDEX IX_EVENTS_TRIP_START ON EVENTS (TRIP_ID, START_TIME);
CREATE INDEX IX_EVENTS_PLACE ON EVENTS (PLACE_ID);

-- ─── TRANSPORTS ─────────────────────────────────────────────────────────────
CREATE TABLE TRANSPORTS (
    ID               NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID              VARCHAR2(36)  NOT NULL,
    TRIP_ID          NUMBER(19)    NOT NULL,
    TRANSPORT_TYPE   VARCHAR2(20)  NOT NULL,                  -- TransportType
    PROVIDER         VARCHAR2(150),
    BOOKING_CODE     VARCHAR2(100),
    DEPARTURE_PLACE  VARCHAR2(300),
    ARRIVAL_PLACE    VARCHAR2(300),
    DEPARTURE_TIME   TIMESTAMP,                               -- UTC
    ARRIVAL_TIME     TIMESTAMP,                               -- UTC
    QR_DATA          VARCHAR2(4000),                          -- decoded QR string (SPEC §2.7), not an image
    NOTE             VARCHAR2(2000),
    CREATED_AT       TIMESTAMP,
    CREATED_BY       NUMBER(19),
    UPDATED_AT       TIMESTAMP,
    UPDATED_BY       NUMBER(19),
    VERSION          NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED       NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TRANSPORTS PRIMARY KEY (ID),
    CONSTRAINT FK_TRANSPORTS_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID)
);
CREATE UNIQUE INDEX UK_TRANSPORTS_RID ON TRANSPORTS (RID);
CREATE INDEX IX_TRANSPORTS_TRIP_DEP ON TRANSPORTS (TRIP_ID, DEPARTURE_TIME);

-- ─── ACCOMMODATIONS ─────────────────────────────────────────────────────────
CREATE TABLE ACCOMMODATIONS (
    ID             NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID            VARCHAR2(36)  NOT NULL,
    TRIP_ID        NUMBER(19)    NOT NULL,
    NAME           VARCHAR2(200) NOT NULL,
    BOOKING_CODE   VARCHAR2(100),
    ADDRESS        VARCHAR2(500),
    CHECKIN_TIME   TIMESTAMP,                                 -- UTC
    CHECKOUT_TIME  TIMESTAMP,                                 -- UTC
    QR_DATA        VARCHAR2(4000),                            -- decoded QR string (SPEC §2.7), not an image
    NOTE           VARCHAR2(2000),
    CREATED_AT     TIMESTAMP,
    CREATED_BY     NUMBER(19),
    UPDATED_AT     TIMESTAMP,
    UPDATED_BY     NUMBER(19),
    VERSION        NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED     NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ACCOMMODATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_ACCOMMODATIONS_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID)
);
CREATE UNIQUE INDEX UK_ACCOMMODATIONS_RID ON ACCOMMODATIONS (RID);
CREATE INDEX IX_ACCOMMODATIONS_TRIP_IN ON ACCOMMODATIONS (TRIP_ID, CHECKIN_TIME);

-- ─── CHECKLIST_ITEMS ────────────────────────────────────────────────────────
CREATE TABLE CHECKLIST_ITEMS (
    ID           NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID          VARCHAR2(36)  NOT NULL,
    TRIP_ID      NUMBER(19)    NOT NULL,
    TITLE        VARCHAR2(300) NOT NULL,
    COMPLETED    NUMBER(1)     DEFAULT 0 NOT NULL,
    ASSIGNEE_ID  NUMBER(19),                                  -- TRIP_MEMBERS.ID, nullable
    SORT_ORDER   NUMBER(10)    DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP,
    CREATED_BY   NUMBER(19),
    UPDATED_AT   TIMESTAMP,
    UPDATED_BY   NUMBER(19),
    VERSION      NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED   NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CHECKLIST_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_CHECKLIST_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID),
    CONSTRAINT FK_CHECKLIST_ASSIGNEE FOREIGN KEY (ASSIGNEE_ID) REFERENCES TRIP_MEMBERS (ID)
);
CREATE UNIQUE INDEX UK_CHECKLIST_ITEMS_RID ON CHECKLIST_ITEMS (RID);
CREATE INDEX IX_CHECKLIST_ITEMS_TRIP ON CHECKLIST_ITEMS (TRIP_ID);
