-- V19 — A checklist is shared by the whole group, but each member ticks their OWN copy (so everyone
-- verifies their pre-trip tasks; no one sees another's checkmarks). Replace the single global
-- COMPLETED flag with a per-member CHECKLIST_COMPLETIONS join (a row = that member completed it).
-- The old global flag can't be attributed to a member, so it's simply dropped (everyone starts fresh).

CREATE TABLE CHECKLIST_COMPLETIONS (
    ID        NUMBER(19)  GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ITEM_ID   NUMBER(19)  NOT NULL,
    MEMBER_ID NUMBER(19)  NOT NULL,
    CONSTRAINT PK_CHECKLIST_COMPLETIONS PRIMARY KEY (ID),
    CONSTRAINT UK_CHECKLIST_COMPLETIONS UNIQUE (ITEM_ID, MEMBER_ID),
    CONSTRAINT FK_CHECKLIST_COMPL_ITEM FOREIGN KEY (ITEM_ID) REFERENCES CHECKLIST_ITEMS (ID),
    CONSTRAINT FK_CHECKLIST_COMPL_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES TRIP_MEMBERS (ID)
);

CREATE INDEX IX_CHECKLIST_COMPL_ITEM ON CHECKLIST_COMPLETIONS (ITEM_ID);
CREATE INDEX IX_CHECKLIST_COMPL_MEMBER ON CHECKLIST_COMPLETIONS (MEMBER_ID);

ALTER TABLE CHECKLIST_ITEMS DROP COLUMN COMPLETED;
