-- V18 — A ticket can belong to MANY members (one booking/room shared by several people), not just
-- one. Replace TICKETS.MEMBER_ID with a TICKET_MEMBERS join. A ticket with no rows here is a "group"
-- ticket (shared by the whole trip, as before with MEMBER_ID NULL). Existing single-owner tickets
-- migrate to one join row; existing group tickets (MEMBER_ID NULL) get none.

CREATE TABLE TICKET_MEMBERS (
    ID        NUMBER(19)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TICKET_ID NUMBER(19)   NOT NULL,
    MEMBER_ID NUMBER(19)   NOT NULL,
    CONSTRAINT PK_TICKET_MEMBERS PRIMARY KEY (ID),
    CONSTRAINT UK_TICKET_MEMBERS UNIQUE (TICKET_ID, MEMBER_ID),
    CONSTRAINT FK_TICKET_MEMBERS_TICKET FOREIGN KEY (TICKET_ID) REFERENCES TICKETS (ID),
    CONSTRAINT FK_TICKET_MEMBERS_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES TRIP_MEMBERS (ID)
);

CREATE INDEX IX_TICKET_MEMBERS_TICKET ON TICKET_MEMBERS (TICKET_ID);
CREATE INDEX IX_TICKET_MEMBERS_MEMBER ON TICKET_MEMBERS (MEMBER_ID);

-- Carry over each existing single-owner ticket as one membership row.
INSERT INTO TICKET_MEMBERS (TICKET_ID, MEMBER_ID)
SELECT ID, MEMBER_ID FROM TICKETS WHERE MEMBER_ID IS NOT NULL;

ALTER TABLE TICKETS DROP COLUMN MEMBER_ID;
