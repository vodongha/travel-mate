-- V6 — Shared fund (M6): FUND_CONTRIBUTIONS, FUND_EXPENSES (SPEC §7 Module 10).
-- The fund balance is derived by aggregation (contributions - fund expenses - personal
-- expenses with PAID_FROM_FUND=1); it is never stored. Settlement (Module 11) is computed
-- on the fly from EXPENSES/EXPENSE_SHARES (V5) and needs no new tables.

-- ─── FUND_CONTRIBUTIONS (money paid into the fund) ──────────────────────────
CREATE TABLE FUND_CONTRIBUTIONS (
    ID             NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID            VARCHAR2(36)  NOT NULL,
    TRIP_ID        NUMBER(19)    NOT NULL,
    MEMBER_ID      NUMBER(19)    NOT NULL,                     -- TRIP_MEMBERS.ID
    CURRENCY       VARCHAR2(3)   NOT NULL,
    AMOUNT         NUMBER(19,4)  NOT NULL,
    EXCHANGE_RATE  NUMBER(19,8)  NOT NULL,
    AMOUNT_BASE    NUMBER(19,4)  NOT NULL,
    NOTE           VARCHAR2(500),
    CREATED_AT     TIMESTAMP,
    CREATED_BY     NUMBER(19),
    UPDATED_AT     TIMESTAMP,
    UPDATED_BY     NUMBER(19),
    VERSION        NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED     NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FUND_CONTRIBUTIONS PRIMARY KEY (ID),
    CONSTRAINT FK_FUND_CONTRIB_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID),
    CONSTRAINT FK_FUND_CONTRIB_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES TRIP_MEMBERS (ID)
);
CREATE UNIQUE INDEX UK_FUND_CONTRIBUTIONS_RID ON FUND_CONTRIBUTIONS (RID);
CREATE INDEX IX_FUND_CONTRIB_TRIP ON FUND_CONTRIBUTIONS (TRIP_ID);
CREATE INDEX IX_FUND_CONTRIB_MEMBER ON FUND_CONTRIBUTIONS (MEMBER_ID);

-- ─── FUND_EXPENSES (money spent out of the fund) ────────────────────────────
CREATE TABLE FUND_EXPENSES (
    ID             NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RID            VARCHAR2(36)  NOT NULL,
    TRIP_ID        NUMBER(19)    NOT NULL,
    TITLE          VARCHAR2(200) NOT NULL,
    CATEGORY       VARCHAR2(20)  NOT NULL,                     -- Category
    CURRENCY       VARCHAR2(3)   NOT NULL,
    AMOUNT         NUMBER(19,4)  NOT NULL,
    EXCHANGE_RATE  NUMBER(19,8)  NOT NULL,
    AMOUNT_BASE    NUMBER(19,4)  NOT NULL,
    NOTE           VARCHAR2(2000),
    CREATED_AT     TIMESTAMP,
    CREATED_BY     NUMBER(19),
    UPDATED_AT     TIMESTAMP,
    UPDATED_BY     NUMBER(19),
    VERSION        NUMBER(10)    DEFAULT 0 NOT NULL,
    IS_DELETED     NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FUND_EXPENSES PRIMARY KEY (ID),
    CONSTRAINT FK_FUND_EXPENSES_TRIP FOREIGN KEY (TRIP_ID) REFERENCES TRIPS (ID)
);
CREATE UNIQUE INDEX UK_FUND_EXPENSES_RID ON FUND_EXPENSES (RID);
CREATE INDEX IX_FUND_EXPENSES_TRIP ON FUND_EXPENSES (TRIP_ID);
